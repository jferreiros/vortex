-- ---- event-window helper (Home / Insights) --------------------------------

create or replace function public.call_events_for_window(
    p_max_calls integer default null,
    p_since timestamptz default null
)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
    with started as (
        select call_id, min(ts) as started_at
        from public.call_events
        group by call_id
    ),
    picked as (
        select s.call_id, s.started_at
        from started s
        where p_since is null or s.started_at >= p_since
        order by s.started_at desc
        -- Never unbounded. jsonb_agg over the whole table exceeds the
        -- statement timeout once the log passes a few hundred calls, and a
        -- timeout here reads as "Supabase is empty" to every caller.
        limit coalesce(p_max_calls, 1000)
    )
    select coalesce(jsonb_agg(e.event order by e.ts), '[]'::jsonb)
    from public.call_events e
    join picked p on p.call_id = e.call_id;
$$;

